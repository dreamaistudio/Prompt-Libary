-- ==============================================================================
-- PROMPT LIBRARY - SUPABASE DATABASE SCHEMA & RLS SETUP
-- ==============================================================================
-- This script sets up all tables, relations, indexes, views, Row Level Security (RLS)
-- policies, storage buckets, and auth triggers required for the Prompt Library app.
-- ==============================================================================

-- 1. Enable UUID Extension (standard in PostgreSQL / Supabase)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- 2. TABLES DEFINITION
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- USERS TABLE
-- Stores public user profiles, linked directly to Supabase Auth users (auth.users)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT DEFAULT '',
    avatar TEXT DEFAULT '',
    email TEXT DEFAULT '',
    totp_secret TEXT DEFAULT '',
    is_totp_enabled BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- PROMPTS TABLE
-- Stores AI prompts (Image & Video) created by users
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.prompts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    prompt TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Image' CHECK (category IN ('Image', 'Video')),
    model TEXT DEFAULT '',
    tags TEXT DEFAULT '',
    thumbnail TEXT DEFAULT '',
    reference_images TEXT DEFAULT '',
    instructions TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ------------------------------------------------------------------------------
-- BOOKMARKS TABLE
-- Stores user favorite/saved prompts with unique constraint per user and prompt
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    prompt_id BIGINT NOT NULL REFERENCES public.prompts(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    CONSTRAINT unique_user_prompt UNIQUE (user_id, prompt_id)
);

-- ==============================================================================
-- 3. INDEXES FOR HIGH-PERFORMANCE SEARCH & SORTING
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);
CREATE INDEX IF NOT EXISTS idx_prompts_user_id ON public.prompts(user_id);
CREATE INDEX IF NOT EXISTS idx_prompts_category ON public.prompts(category);
CREATE INDEX IF NOT EXISTS idx_prompts_created_at ON public.prompts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bookmarks_user_id ON public.bookmarks(user_id);
CREATE INDEX IF NOT EXISTS idx_bookmarks_prompt_id ON public.bookmarks(prompt_id);

-- Full-text / Trigram search indexes (optional acceleration)
CREATE INDEX IF NOT EXISTS idx_prompts_title_trgm ON public.prompts USING gin (to_tsvector('english', title));
CREATE INDEX IF NOT EXISTS idx_prompts_prompt_trgm ON public.prompts USING gin (to_tsvector('english', prompt));

-- ==============================================================================
-- 4. VIEW: PROMPTS WITH AUTHOR USERNAME
-- Provides flat, joined data including the author username for clean frontend queries
-- ==============================================================================
CREATE OR REPLACE VIEW public.prompts_with_author AS
SELECT
    p.id,
    p.user_id,
    p.title,
    p.prompt,
    p.category,
    p.model,
    p.tags,
    p.thumbnail,
    p.reference_images,
    p.instructions,
    p.created_at,
    COALESCE(u.username, 'Unknown') AS author
FROM public.prompts p
LEFT JOIN public.users u ON p.user_id = u.id;

-- ==============================================================================
-- 5. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

-- Enable RLS on all tables
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prompts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookmarks ENABLE ROW LEVEL SECURITY;

-- ------------------------------------------------------------------------------
-- POLICIES FOR: public.users
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Public users profiles are viewable by everyone" ON public.users;
CREATE POLICY "Public users profiles are viewable by everyone"
    ON public.users FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Users can insert their own profile" ON public.users;
CREATE POLICY "Users can insert their own profile"
    ON public.users FOR INSERT
    WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update their own profile" ON public.users;
CREATE POLICY "Users can update their own profile"
    ON public.users FOR UPDATE
    USING (auth.uid() = id)
    WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can delete their own profile" ON public.users;
CREATE POLICY "Users can delete their own profile"
    ON public.users FOR DELETE
    USING (auth.uid() = id);

-- ------------------------------------------------------------------------------
-- POLICIES FOR: public.prompts
-- Any user can view prompts, but only the owner can modify or delete them
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Prompts are viewable by everyone" ON public.prompts;
CREATE POLICY "Prompts are viewable by everyone"
    ON public.prompts FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Authenticated users can insert prompts" ON public.prompts;
CREATE POLICY "Authenticated users can insert prompts"
    ON public.prompts FOR INSERT
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own prompts" ON public.prompts;
CREATE POLICY "Users can update their own prompts"
    ON public.prompts FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own prompts" ON public.prompts;
CREATE POLICY "Users can delete their own prompts"
    ON public.prompts FOR DELETE
    USING (auth.uid() = user_id);

-- ------------------------------------------------------------------------------
-- POLICIES FOR: public.bookmarks
-- Users can only read, insert, and delete their own bookmarks
-- ------------------------------------------------------------------------------
DROP POLICY IF EXISTS "Users can view their own bookmarks" ON public.bookmarks;
CREATE POLICY "Users can view their own bookmarks"
    ON public.bookmarks FOR SELECT
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own bookmarks" ON public.bookmarks;
CREATE POLICY "Users can insert their own bookmarks"
    ON public.bookmarks FOR INSERT
    WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own bookmarks" ON public.bookmarks;
CREATE POLICY "Users can delete their own bookmarks"
    ON public.bookmarks FOR DELETE
    USING (auth.uid() = user_id);

-- ==============================================================================
-- 6. AUTH TRIGGER: AUTO-CREATE PUBLIC.USERS PROFILE
-- When a user registers through Supabase Auth (or Netlify Function), their
-- public profile in public.users is automatically created or synced.
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    clean_username TEXT;
BEGIN
    -- Extract username from user_metadata or default to email prefix
    clean_username := COALESCE(
        NEW.raw_user_meta_data->>'username',
        split_part(NEW.email, '@', 1)
    );

    INSERT INTO public.users (id, username, email, created_at)
    VALUES (
        NEW.id,
        clean_username,
        COALESCE(NEW.email, ''),
        COALESCE(NEW.created_at, TIMEZONE('utc'::text, NOW()))
    )
    ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email,
        username = CASE
            WHEN public.users.username IS NULL OR public.users.username = '' THEN EXCLUDED.username
            ELSE public.users.username
        END;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ==============================================================================
-- 7. STORAGE BUCKETS CONFIGURATION (thumbnails & avatars)
-- Sets up public read access for thumbnails and avatars
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('thumbnails', 'thumbnails', true),
       ('avatars', 'avatars', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS Policies for thumbnails
DROP POLICY IF EXISTS "Public Access Thumbnails" ON storage.objects;
CREATE POLICY "Public Access Thumbnails"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'thumbnails');

DROP POLICY IF EXISTS "Authenticated users upload thumbnails" ON storage.objects;
CREATE POLICY "Authenticated users upload thumbnails"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'thumbnails' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Users update own thumbnails" ON storage.objects;
CREATE POLICY "Users update own thumbnails"
    ON storage.objects FOR UPDATE
    USING (bucket_id = 'thumbnails' AND auth.uid() = owner);

DROP POLICY IF EXISTS "Users delete own thumbnails" ON storage.objects;
CREATE POLICY "Users delete own thumbnails"
    ON storage.objects FOR DELETE
    USING (bucket_id = 'thumbnails' AND auth.uid() = owner);

-- Storage RLS Policies for avatars
DROP POLICY IF EXISTS "Public Access Avatars" ON storage.objects;
CREATE POLICY "Public Access Avatars"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'avatars');

DROP POLICY IF EXISTS "Authenticated users upload avatars" ON storage.objects;
CREATE POLICY "Authenticated users upload avatars"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'avatars' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Users update own avatars" ON storage.objects;
CREATE POLICY "Users update own avatars"
    ON storage.objects FOR UPDATE
    USING (bucket_id = 'avatars' AND auth.uid() = owner);

DROP POLICY IF EXISTS "Users delete own avatars" ON storage.objects;
CREATE POLICY "Users delete own avatars"
    ON storage.objects FOR DELETE
    USING (bucket_id = 'avatars' AND auth.uid() = owner);

-- ==============================================================================
-- 8. SCHEMA PERMISSIONS
-- Grant appropriate access to PostgREST roles (anon, authenticated, service_role)
-- ==============================================================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;
GRANT SELECT ON public.prompts_with_author TO anon, authenticated, service_role;
